-- Schema PostgreSQL para Supabase

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  role VARCHAR(10) NOT NULL DEFAULT 'user'
    CHECK (role IN ('user', 'mod', 'adm')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS purchase (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_user INTEGER NOT NULL REFERENCES users(id),
  datahora TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  all_price NUMERIC(15, 2),
  status VARCHAR(20)
    CHECK (status IN ('aberto', 'fechado', 'cancelado'))
);

CREATE TABLE IF NOT EXISTS stores (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_owner INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  store_name VARCHAR(120) NOT NULL,
  niche VARCHAR(60) NOT NULL,
  description VARCHAR(255) NOT NULL,
  logo VARCHAR(255),
  banner VARCHAR(255),
  contact_email VARCHAR(100) NOT NULL,
  contact_phone VARCHAR(15) NOT NULL,
  cnpj VARCHAR(100) NOT NULL,
  slug VARCHAR(120) NOT NULL UNIQUE,
  status VARCHAR(20) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'active', 'rejected')),
  admin_notes VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS products (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_store INTEGER NOT NULL REFERENCES stores(id) ON DELETE CASCADE,
  name VARCHAR(120) NOT NULL,
  description VARCHAR(255) NOT NULL,
  price NUMERIC(10, 2) NOT NULL,
  stock INTEGER NOT NULL,
  image VARCHAR(255) NOT NULL,
  category VARCHAR(60) NOT NULL,
  slug VARCHAR(120) NOT NULL UNIQUE,
  discount NUMERIC(5, 2),
  status VARCHAR(20) NOT NULL DEFAULT 'active'
    CHECK (status IN ('active', 'draft')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS items (
  id_purchase INTEGER NOT NULL REFERENCES purchase(id) ON DELETE CASCADE,
  id_product INTEGER NOT NULL REFERENCES products(id),
  quantity NUMERIC NOT NULL,
  unit_value NUMERIC(15, 2),
  PRIMARY KEY (id_purchase, id_product)
);

CREATE TABLE IF NOT EXISTS payment_methods (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(50) NOT NULL,
  slug VARCHAR(50) NOT NULL UNIQUE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS payments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES purchase(id),
  user_id INTEGER NOT NULL REFERENCES users(id),
  payment_method_id INTEGER NOT NULL REFERENCES payment_methods(id),
  amount NUMERIC(10, 2) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'approved', 'failed', 'refunded')),
  gateway_id VARCHAR(255),
  invoice_url VARCHAR(255),
  paid_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_addresses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  state VARCHAR(100) NOT NULL,
  city VARCHAR(100) NOT NULL,
  cep VARCHAR(20) NOT NULL,
  neighborhood VARCHAR(100) NOT NULL,
  street VARCHAR(255) NOT NULL,
  number VARCHAR(45) NOT NULL,
  complement VARCHAR(100),
  full_name VARCHAR(255) NOT NULL,
  phone_number VARCHAR(20) NOT NULL,
  address_name VARCHAR(100),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_purchase_user_id
  ON purchase (id_user);

CREATE INDEX IF NOT EXISTS idx_stores_owner
  ON stores (id_owner);

CREATE INDEX IF NOT EXISTS idx_products_store
  ON products (id_store);

CREATE INDEX IF NOT EXISTS idx_items_product
  ON items (id_product);

CREATE INDEX IF NOT EXISTS idx_payments_method
  ON payments (payment_method_id);

CREATE INDEX IF NOT EXISTS idx_addresses_user
  ON user_addresses (user_id);